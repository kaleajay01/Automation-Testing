from playwright.sync_api import expect

def test_assign_assessment_navigation(shared_page):
    expect(shared_page).to_have_url("http://localhost:8081/models/membership/dashboard")
    print("Dashboard opened successfully")
    assign_assessment = shared_page.get_by_text("Assign Assessment",exact=True)
    expect(assign_assessment).to_be_visible()
    assign_assessment.click()
    print("Assign Assessment card clicked")
    expect(shared_page).to_have_url("http://localhost:8081/models/assign-assessment",timeout=15000)
    print("Assign Assessment page opened successfully")

